## doResprouting(): a species resprouts in a burned pixelGroup if any of its burned cohorts there is
## within its resprout age range (as LANDIS-II's Reproduction.CheckForResprouting() does per killed
## cohort), not only if the oldest one is. Light and resprout probabilities are 1 here, so every
## eligible species-pixel resprouts.

resproutFixture <- function() {
  spp <- c("Pinu_ban", "Popu_tre")
  species <- data.table(
    speciesCode = factor(spp, levels = spp),
    postfireregen = c("serotiny", "resprout"),
    resproutage_min = c(0L, 10L),
    resproutage_max = c(0L, 150L),
    resproutprob = c(0, 1),
    shadetolerance = c(1, 1)
  )
  sufficientLight <- data.frame(
    speciesshadetolerance = 1:5,
    X0 = 1, X1 = 1, X2 = 1, X3 = 1, X4 = 1, X5 = 1
  )

  ## pixelGroup 1 (pixels 1, 2): aspen past resproutage_max, plus two younger aspen in range.
  ## pixelGroup 2 (pixels 3, 4): aspen past resproutage_max and below resproutage_min only.
  ## cohorts are listed oldest first within each pixelGroup, as in cohortData.
  cohortData <- data.table(
    pixelGroup = c(1L, 1L, 1L, 1L, 2L, 2L),
    ecoregionGroup = factor("1_01"),
    speciesCode = factor(c("Pinu_ban", rep("Popu_tre", 5)), levels = spp),
    age = c(60L, 160L, 80L, 40L, 200L, 5L)
  )
  treedFirePixelTableSinceLastDisp <- data.table(
    pixelIndex = 1:4,
    pixelGroup = c(1L, 1L, 2L, 2L),
    burnTime = 1L
  )

  ## expand to burned pixels, as FireDisturbance() does
  burnedPixelCohortData <- treedFirePixelTableSinceLastDisp[cohortData,
    allow.cartesian = TRUE,
    nomatch = 0, on = "pixelGroup"
  ]
  set(burnedPixelCohortData, NULL, c("sumB", "siteShade"), 0)
  setkey(burnedPixelCohortData, speciesCode)

  ## jack pine regenerated by serotiny in pixel 1
  serotinyRegen <- data.table(
    pixelGroup = 1L, ecoregionGroup = factor("1_01"),
    speciesCode = factor("Pinu_ban", levels = spp), pixelIndex = 1L, type = "serotiny"
  )

  list(
    burnedPixelCohortData = burnedPixelCohortData,
    treedFirePixelTableSinceLastDisp = treedFirePixelTableSinceLastDisp,
    species = species,
    sufficientLight = sufficientLight,
    serotinyRegen = serotinyRegen
  )
}

runResprouting <- function(fx, serotiny = TRUE) {
  doResprouting(
    burnedPixelCohortData = fx$burnedPixelCohortData,
    postFirePixelCohortData = if (serotiny) fx$serotinyRegen else fx$serotinyRegen[0],
    serotinyPixel = if (serotiny) unique(fx$serotinyRegen$pixelIndex) else NULL,
    treedFirePixelTableSinceLastDisp = copy(fx$treedFirePixelTableSinceLastDisp),
    currentTime = 1L,
    species = fx$species,
    sufficientLight = fx$sufficientLight
  )
}

test_that("doResprouting() resprouts a species whose younger cohort is in range, not its oldest", {
  withr::local_seed(1)
  fx <- resproutFixture()
  out <- runResprouting(fx, serotiny = TRUE)

  resprouts <- out$postFirePixelCohortData[type == "resprouting"]
  ## one record per species and pixel, in both pixels of pixelGroup 1; aspen resprouts in pixel 1
  ## although jack pine regenerated there by serotiny
  expect_setequal(resprouts$pixelIndex, c(1L, 2L))
  expect_false(anyDuplicated(resprouts, by = c("pixelIndex", "speciesCode")) > 0)
  expect_identical(as.character(unique(resprouts$speciesCode)), "Popu_tre")
  expect_setequal(out$serotinyResproutSuccessPixels, c(1L, 2L))

  ## the serotiny record is kept
  expect_identical(nrow(out$postFirePixelCohortData[type == "serotiny"]), 1L)
})

test_that("doResprouting() does not resprout a species with no cohort in its resprout age range", {
  fx <- resproutFixture()
  for (serotiny in c(TRUE, FALSE)) {
    withr::local_seed(1)
    out <- runResprouting(fx, serotiny = serotiny)
    resprouts <- out$postFirePixelCohortData[type == "resprouting"]
    expect_false(any(resprouts$pixelIndex %in% c(3L, 4L)))
    expect_false(any(out$serotinyResproutSuccessPixels %in% c(3L, 4L)))
  }
})
